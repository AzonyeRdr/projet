CREATE TABLE IF NOT EXISTS utilisateur (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(50),
    prenom VARCHAR(50),
    idRole INTEGER,
    CONSTRAINT fk_util_role FOREIGN KEY (idRole) REFERENCES role(id)
);


CREATE TABLE IF NOT EXISTS patient (
    idVital VARCHAR(50) PRIMARY KEY,
    idUtilisateur INTEGER NOT NULL UNIQUE,
    lieuNaissance VARCHAR(100),
    dateNaissance DATE,
    marie BOOLEAN,
    genre VARCHAR(30),
    CONSTRAINT fk_patient_utilisateur
        FOREIGN KEY (idUtilisateur)
        REFERENCES utilisateur(id)
);

